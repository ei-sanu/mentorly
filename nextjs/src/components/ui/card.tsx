import * as React from "react"
import { cn } from "@/lib/utils"

// Mentorly light card (2026-11-11, white theme): a flat white card with a
// hairline border and dark text, matching the home page. The old dark
// glass is gone from globals.css; the `glass-panel` class name is kept so
// existing markup keeps working.
const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "glass-panel rounded-lg text-neutral-900",
        className
      )}
      {...props}
    />
  )
)
Card.displayName = "Card"

